// Generates src/engine/trig-table.ts — the FROZEN sine table.
// Run once; the emitted base64 constant is the canonical table for every machine.
import { writeFileSync } from "node:fs";

const TABLE_BITS = 12;
const TABLE_SIZE = 1 << TABLE_BITS; // 4096
const ONE = 65536; // Q16.16

const buf = new Int32Array(TABLE_SIZE);
for (let i = 0; i < TABLE_SIZE; i++) {
  buf[i] = Math.round(Math.sin((i / TABLE_SIZE) * Math.PI * 2) * ONE);
}
const b64 = Buffer.from(buf.buffer).toString("base64");

const out = `// GENERATED by scripts/gen-trig-table.mjs — do not edit by hand.
// The frozen Q16.16 sine table: SIN[i] = round(sin(i / ${TABLE_SIZE} * 2pi) * 65536).
// This constant is the canonical table on every machine (see docs/PHASES.md P3).

export const TABLE_BITS = ${TABLE_BITS};
export const TABLE_SIZE = ${TABLE_SIZE};

const B64 =
  "${b64}";

function decode(): Int32Array {
  const bin = typeof atob === "function"
    ? atob(B64)
    : Buffer.from(B64, "base64").toString("binary");
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new Int32Array(bytes.buffer);
}

export const SIN_TABLE: Int32Array = decode();
`;
writeFileSync("src/engine/trig-table.ts", out);
console.log(`wrote src/engine/trig-table.ts (${TABLE_SIZE} entries, ${b64.length} b64 chars)`);
